#!/usr/bin/env python3
"""Compare the three correctly flagged and four missed GOLD reversals.
Reads gold_turn_validation/labeled_signal_features.csv (lag 1 signals).
Does not refit thresholds or use future outcomes to create signals.
"""
import argparse
from pathlib import Path
import numpy as np
import pandas as pd

HITS=['2023-02-01','2025-04-23','2026-09-03']
MISSES=['2025-05-08','2025-10-23','2026-01-29','2026-03-02']
FOCUS=['body_pct_range','upper_wick_pct_range','close_location_pct','range_pct',
'rsi_7','rsi_14','rsi_21','rsi_14_change_1','rsi_change_3','rsi_change_5','rsi_change_10',
'macd_hist_pct','macd_hist_pct_change_1','macd_hist_change_3','macd_hist_change_5','macd_hist_change_10','macd_hist_accel',
'adx_14','adx_14_change_1','adx_change_5','plus_di_14','minus_di_14','di_spread',
'atr_14_pct','atr_14_pct_change_1','atr_vs_range','volatility_3','volatility_5','volatility_10',
'rvol_5','rvol_10','rvol_20','volume_trend_5','volume_trend_10',
'mfi_14','mfi_14_change_1','cmf_20','cmf_20_change_1',
'return_5_pct','return_10_pct','return_20_pct','distance_ema_9_pct','distance_ema_20_pct','distance_ema_50_pct',
'bollinger_position_20','stoch_14','cci_20','rsi_divergence_10','macd_divergence_10']

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--data',default='/app/gold_turn_validation/labeled_signal_features.csv')
    p.add_argument('--out',default='/app/gold_seven_comparison')
    a=p.parse_args()
    df=pd.read_csv(a.data)
    df['date']=pd.to_datetime(df['date'],errors='coerce').dt.strftime('%Y-%m-%d')
    all_dates=HITS+MISSES
    sel=df[df.date.isin(all_dates)].copy()
    missing=set(all_dates)-set(sel.date)
    if missing:raise SystemExit('Missing dates in saved feature file: '+', '.join(sorted(missing)))
    sel['group']=np.where(sel.date.isin(HITS),'CORRECT','MISSED')
    sel['prediction_body']=(sel.group=='CORRECT').astype(int)
    sel['signal_lag_note']='Features were generated by gold_turn_validation with --lag 1 (default)'
    selected=['date','group','close','prior_rise_pct','prior_high_distance_pct','label','hit_bar','max_up_pct','max_down_pct'] + [c for c in FOCUS if c in sel.columns]
    selected=list(dict.fromkeys(c for c in selected if c in sel.columns))
    sel=sel.sort_values('date')
    out=Path(a.out);out.mkdir(parents=True,exist_ok=True)
    sel[selected].to_csv(out/'seven_dates_all_features.csv',index=False,encoding='utf-8-sig')
    rows=[]
    for f in [c for c in FOCUS if c in sel.columns]:
        vals=pd.to_numeric(sel[f],errors='coerce')
        g1=vals[sel.group=='CORRECT'].dropna();g2=vals[sel.group=='MISSED'].dropna()
        if len(g1)<2 or len(g2)<2:continue
        med1=g1.median();med2=g2.median()
        spread=abs(med1-med2)
        pooled=np.nanstd(pd.concat([g1,g2]),ddof=1)
        rows.append({'indicator':f,'correct_mean':g1.mean(),'missed_mean':g2.mean(),
        'correct_median':med1,'missed_median':med2,
        'mean_difference_correct_minus_missed':g1.mean()-g2.mean(),
        'std_separation':spread/pooled if pooled>0 else np.nan,
        'correct_min':g1.min(),'correct_max':g1.max(),
        'missed_min':g2.min(),'missed_max':g2.max(),
        'ranges_overlap':not(g1.max()<g2.min() or g2.max()<g1.min())})
    result=pd.DataFrame(rows).sort_values('std_separation',ascending=False,na_position='last')
    result.to_csv(out/'group_indicator_comparison.csv',index=False,encoding='utf-8-sig')
    for group in ['CORRECT','MISSED']:
        print('\n'+'='*80+'\n'+group+' REVERSALS\n'+'='*80)
        c=['date','close','body_pct_range','rsi_14','rsi_14_change_1','macd_hist_pct',
          'macd_hist_pct_change_1','adx_14','atr_14_pct','atr_14_pct_change_1',
          'rvol_20','mfi_14','cmf_20','return_20_pct','max_down_pct']
        print(sel.loc[sel.group==group,[x for x in c if x in sel]].round(3).to_string(index=False))
    print('\nTOP DIFFERENCES BETWEEN GROUPS (DESCRIPTIVE, NOT PREDICTIVE):')
    show=['indicator','correct_mean','missed_mean','mean_difference_correct_minus_missed','std_separation','ranges_overlap']
    print(result[show].head(25).round(4).to_string(index=False))
    print('\nFILES:',out/'seven_dates_all_features.csv',out/'group_indicator_comparison.csv')
    print('WARNING: Seven known reversals are too few for a reliable separator. Lag-1 features, if the input used default --lag 1. No out-of-sample validity claimed.')

if __name__=='__main__':main()
